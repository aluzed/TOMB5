#!/usr/bin/env python3
"""Compile the Vulkan GLSL shaders with glslc and emit EMULATOR/SHADERS_VK.H.

Usage: python3 scripts/porting/gen_vk_shaders.py
Requires glslc (shaderc).  The generated header is committed so the game
build does not depend on glslc.
"""

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SHADERS = ROOT / "EMULATOR" / "SHADERS"
OUT = ROOT / "EMULATOR" / "SHADERS_VK.H"

SOURCES = [
    ("psx_vert", "psx.vert", "vert"),
    ("psx4_frag", "psx4.frag", "frag"),
    ("psx8_frag", "psx8.frag", "frag"),
    ("psx16_frag", "psx16.frag", "frag"),
    ("blit_vert", "blit.vert", "vert"),
    ("blit_frag", "blit.frag", "frag"),
    ("post_vert", "post.vert", "vert"),
    ("post_frag", "post.frag", "frag"),
]


def compile_one(stage, source, out_path):
    cmd = ["glslc", "-fshader-stage=" + stage, str(SHADERS / source), "-o", str(out_path)]
    if stage == "frag":
        cmd[1:1] = ["-I", str(SHADERS)]
    subprocess.run(cmd, check=True)


def emit_array(name, data):
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    lines = ["static const uint32_t %s_spv[] = {" % name]
    for i in range(0, len(words), 6):
        lines.append("    " + ", ".join("0x%08xu" % w for w in words[i:i + 6]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = [
        "/* Generated by scripts/porting/gen_vk_shaders.py from EMULATOR/SHADERS. */",
        "#ifndef SHADERS_VK_H",
        "#define SHADERS_VK_H",
        "#include <stdint.h>",
        "",
    ]
    for name, source, stage in SOURCES:
        spv = Path("/tmp") / (name + ".spv")
        compile_one(stage, source, spv)
        parts.append(emit_array(name, spv.read_bytes()))
        parts.append("")
    parts.append("#endif")
    OUT.write_text("\n".join(parts) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
